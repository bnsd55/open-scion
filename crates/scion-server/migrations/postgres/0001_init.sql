-- Scion metadata schema for Postgres, version 1.
--
-- It holds the same tables as the SQLite schema at version 6
-- (migrations/0001..0006): a drift test opens both and compares every
-- table, column and kind, so a change to one file must change the other.
-- Blobs live in the object folder. Trees live here, so a derivation that
-- writes many trees commits them in one transaction.
--
-- Every connection sets synchronous_commit = on, so a commit is durable
-- when the statement returns. Refs and lands move only by compare-and-swap
-- on a version or a state, so READ COMMITTED is enough: a lost swap takes
-- the caller's retry path, as on SQLite.

CREATE TABLE repos (
    repo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    TEXT NOT NULL UNIQUE
);

-- Changesets are global and content-addressed. `gen` is graph metadata
-- (1 + the highest parent gen) and is not part of the hash.
CREATE TABLE changesets (
    id   BYTEA PRIMARY KEY CHECK (octet_length(id) = 32),
    gen  BIGINT NOT NULL CHECK (gen >= 1),
    body BYTEA NOT NULL
);

CREATE TABLE changeset_parents (
    cs     BYTEA NOT NULL REFERENCES changesets (id),
    n      BIGINT NOT NULL CHECK (n >= 0),
    parent BYTEA NOT NULL REFERENCES changesets (id),
    PRIMARY KEY (cs, n)
);

CREATE INDEX changeset_parents_by_parent ON changeset_parents (parent);

-- Which changesets a repository may read. Authorization goes through here.
CREATE TABLE repo_changesets (
    repo_id BIGINT NOT NULL REFERENCES repos (repo_id),
    cs      BYTEA NOT NULL REFERENCES changesets (id),
    PRIMARY KEY (repo_id, cs)
);

-- A ref moves only by compare-and-swap on `version`.
CREATE TABLE refs (
    repo_id BIGINT NOT NULL,
    name    TEXT NOT NULL,
    target  BYTEA NOT NULL,
    version BIGINT NOT NULL,
    PRIMARY KEY (repo_id, name),
    FOREIGN KEY (repo_id, target) REFERENCES repo_changesets (repo_id, cs)
);

-- One row per land request. A retry with the same (repo, caller, key) finds
-- this row. `conflict_paths` holds the paths joined by NUL bytes, which a
-- path cannot contain. `land_id` comes from the identity sequence, so no ID
-- is given out twice and the newest land always has the largest one.
CREATE TABLE lands (
    land_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_id        BIGINT NOT NULL REFERENCES repos (repo_id),
    caller         TEXT NOT NULL,
    request_key    TEXT NOT NULL,
    target_ref     TEXT NOT NULL,
    input_cs       BYTEA NOT NULL REFERENCES changesets (id),
    state          TEXT NOT NULL CHECK (state IN ('pending', 'landed', 'conflict', 'rejected')),
    result_cs      BYTEA REFERENCES changesets (id),
    detail         TEXT NOT NULL DEFAULT '',
    conflict_paths BYTEA NOT NULL DEFAULT ''::bytea,
    finished_at    BIGINT,
    created_at     BIGINT NOT NULL DEFAULT 0,
    UNIQUE (repo_id, caller, request_key),
    CHECK ((state = 'landed') = (result_cs IS NOT NULL))
);

-- Finds the oldest finished lands without a scan of the table.
CREATE INDEX lands_by_finished_at ON lands (finished_at) WHERE finished_at IS NOT NULL;

-- Finds the oldest pending lands without a scan of the table.
CREATE INDEX lands_pending_by_created_at ON lands (created_at) WHERE state = 'pending';

-- TreeV1 objects (docs/format-v1.md), keyed by TreeId.
CREATE TABLE trees (
    id   BYTEA PRIMARY KEY CHECK (octet_length(id) = 32),
    body BYTEA NOT NULL
);

-- Derived data: one value per (kind, version, changeset). Rebuildable.
CREATE TABLE derived (
    kind    TEXT NOT NULL,
    version BIGINT NOT NULL,
    cs      BYTEA NOT NULL REFERENCES changesets (id),
    value   BYTEA NOT NULL,
    PRIMARY KEY (kind, version, cs)
);

-- Git commits already imported, for incremental re-import.
CREATE TABLE git_import (
    repo_id  BIGINT NOT NULL REFERENCES repos (repo_id),
    git_algo BIGINT NOT NULL CHECK (git_algo IN (1, 2)),
    git_oid  BYTEA NOT NULL,
    cs       BYTEA NOT NULL REFERENCES changesets (id),
    PRIMARY KEY (repo_id, git_algo, git_oid)
);

-- The blobs that a repo may name: those uploaded to it, and those that its
-- changesets name. Blob files are shared by all repos, so without this a
-- changeset could name another repo's blob by ID and then read it.
CREATE TABLE repo_blobs (
    repo_id BIGINT NOT NULL REFERENCES repos (repo_id),
    blob    BYTEA NOT NULL CHECK (octet_length(blob) = 32),
    PRIMARY KEY (repo_id, blob)
);

-- Nodes of path history trees: one directory level, keyed by the BLAKE3
-- hash of its body. Derived data: rebuildable from changesets.
CREATE TABLE history_nodes (
    id   BYTEA PRIMARY KEY CHECK (octet_length(id) = 32),
    body BYTEA NOT NULL
);

-- The database server's time, in Unix seconds: what SQLite's `unixepoch()`
-- gives, so the two backends age lands the same way.
CREATE FUNCTION now_epoch() RETURNS BIGINT LANGUAGE SQL IMMUTABLE PARALLEL SAFE
    RETURN extract(epoch FROM now())::bigint;
